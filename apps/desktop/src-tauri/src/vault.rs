//! Provider credentials in the OS credential store (Windows Credential Manager, macOS Keychain). The
//! database keeps only a reference; the secret never crosses into the interface (plan §2.3, ADR-002).

// The engineering name, kept when the product became Pygg: keys already stored under it must stay readable.
const SERVICE: &str = "SmartTaskRouter";

#[derive(Debug)]
pub enum VaultError {
    /// The credential store refused or is unavailable. The message never contains the secret.
    Store(String),
    InvalidReference,
}

impl std::fmt::Display for VaultError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            VaultError::Store(message) => write!(f, "Credential store error: {message}"),
            VaultError::InvalidReference => write!(f, "Invalid credential reference"),
        }
    }
}

impl std::error::Error for VaultError {}

/// A fresh reference for a new credential, e.g. `provider-3f2a…`.
pub fn new_reference() -> String {
    format!("provider-{}", uuid::Uuid::new_v4().simple())
}

fn entry(reference: &str) -> Result<keyring::Entry, VaultError> {
    // References are generated by new_reference(); anything else is a programming error or tampering.
    let valid = reference.len() <= 64
        && reference.starts_with("provider-")
        && reference.chars().all(|c| c.is_ascii_alphanumeric() || c == '-');
    if !valid {
        return Err(VaultError::InvalidReference);
    }
    keyring::Entry::new(SERVICE, reference).map_err(|e| VaultError::Store(e.to_string()))
}

pub fn store(reference: &str, secret: &str) -> Result<(), VaultError> {
    entry(reference)?.set_password(secret).map_err(|e| VaultError::Store(e.to_string()))
}

/// The secret, or `None` when no credential exists under this reference.
pub fn read(reference: &str) -> Result<Option<String>, VaultError> {
    match entry(reference)?.get_password() {
        Ok(secret) => Ok(Some(secret)),
        Err(keyring::Error::NoEntry) => Ok(None),
        Err(e) => Err(VaultError::Store(e.to_string())),
    }
}

/// Removes the credential; removing one that does not exist is not an error.
pub fn remove(reference: &str) -> Result<(), VaultError> {
    match entry(reference)?.delete_credential() {
        Ok(()) | Err(keyring::Error::NoEntry) => Ok(()),
        Err(e) => Err(VaultError::Store(e.to_string())),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rejects_foreign_references() {
        assert!(matches!(read("../other-app"), Err(VaultError::InvalidReference)));
        assert!(matches!(read("provider-a b"), Err(VaultError::InvalidReference)));
        assert!(new_reference().starts_with("provider-"));
    }

    /// Touches the real OS credential store, so it only runs on request: `cargo test -- --ignored`.
    #[test]
    #[ignore]
    fn round_trip_in_os_store() {
        let reference = new_reference();
        store(&reference, "test-secret-value").unwrap();
        assert_eq!(read(&reference).unwrap().as_deref(), Some("test-secret-value"));
        remove(&reference).unwrap();
        assert_eq!(read(&reference).unwrap(), None);
    }
}
